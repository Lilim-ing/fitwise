"""Deterministic sizing.

This is the part of the assistant that must never be generated by a model: the
mapping from two measurements to a size is arithmetic, and an LLM that gets it
slightly wrong produces a confidently wrong answer.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field

BANDS = [65, 70, 75, 80, 85, 90, 95, 100]
CUPS = ["AA", "A", "B", "C", "D", "E", "F", "G"]

# Upper bound (cm) for each cup; the value is the midpoint between ISO steps of
# 2.5cm, so a measurement sitting exactly on a boundary still lands somewhere
# defensible instead of depending on float equality.
CUP_LIMITS = [8.75, 11.25, 13.75, 16.25, 18.75, 21.25, 23.75]

MIN_UNDERBUST, MAX_UNDERBUST = 55.0, 115.0


@dataclass
class FitResult:
    ok: bool
    band: int = 0
    cup: str = ""
    size: str = ""
    diff_cm: float = 0.0
    sister_sizes: list[str] = field(default_factory=list)
    confidence: str = "high"
    notes: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "ok": self.ok,
            "band": self.band,
            "cup": self.cup,
            "size": self.size,
            "diff_cm": self.diff_cm,
            "sister_sizes": self.sister_sizes,
            "confidence": self.confidence,
            "notes": self.notes,
        }


def to_band(underbust: float) -> int:
    """Snap to the nearest 5cm band, clamped to the supported range.

    Rounds half up: an exact midpoint (72.5) goes to the larger band, which is
    the common fitting convention. Python's built-in round() would send it to
    the even band and make 72.5 -> 70.
    """
    if not MIN_UNDERBUST <= underbust <= MAX_UNDERBUST:
        raise ValueError(f"下胸围 {underbust}cm 超出可选范围 {MIN_UNDERBUST:.0f}-{MAX_UNDERBUST:.0f}cm")
    snapped = int((underbust + 2.5) // 5 * 5)
    return int(min(max(snapped, BANDS[0]), BANDS[-1]))


def to_cup(diff: float) -> tuple[str, int, float]:
    """Return (cup, index, distance to the nearest cup boundary).

    The distance must be measured to *either* adjacent boundary. Checking only
    the upper bound makes a measurement just above a boundary (11.3cm) look
    comfortably far from it, which suppresses the low-confidence warning.
    """
    index = next((i for i, limit in enumerate(CUP_LIMITS) if diff < limit), len(CUPS) - 1)
    gap = min(abs(diff - boundary) for boundary in CUP_LIMITS)
    return CUPS[index], index, gap


def sister_sizes(band: int, cup_index: int) -> list[str]:
    """Same cup volume, different band.

    Smaller band -> the cup must go UP one step to hold the same volume;
    larger band -> the cup goes DOWN one step. Getting this backwards produces
    a size that looks plausible and fits badly.
    """
    out = []
    if cup_index + 1 < len(CUPS) and band - 5 >= BANDS[0]:
        out.append(f"{band - 5}{CUPS[cup_index + 1]}")
    if cup_index > 0 and band + 5 <= BANDS[-1]:
        out.append(f"{band + 5}{CUPS[cup_index - 1]}")
    return out


def compute(underbust: float, bust: float) -> FitResult:
    try:
        u = float(underbust)
        b = float(bust)
    except (TypeError, ValueError):
        return FitResult(ok=False, notes=["测量值必须是数字，请重新输入"])

    if not (math.isfinite(u) and math.isfinite(b)):
        return FitResult(ok=False, notes=["测量值必须是有限数字，请重新输入"])

    try:
        band = to_band(u)
    except ValueError as exc:
        return FitResult(ok=False, notes=[str(exc)])

    diff = b - u
    if diff <= 0:
        return FitResult(ok=False, notes=["上胸围应大于下胸围，请复测：上胸围绕乳房最高点一周"])

    cup, index, gap = to_cup(diff)
    notes: list[str] = []
    confidence = "high"

    if gap < 0.6:
        confidence = "medium"
        notes.append(
            f"围差 {diff:.1f}cm 接近 {cup} 与相邻杯的分界，建议同尺码区间内试两个杯型"
        )
    if diff > 23.75:
        confidence = "low"
        notes.append("围差超过 G 杯范围，建议线下试穿或咨询客服确认杯深")

    return FitResult(
        ok=True,
        band=band,
        cup=cup,
        size=f"{band}{cup}",
        diff_cm=round(diff, 1),
        sister_sizes=sister_sizes(band, index),
        confidence=confidence,
        notes=notes,
    )


def parse_size(size: str) -> tuple[int, str] | None:
    """Parse '75C' / '75 C' / '75c' into (band, cup)."""
    text = str(size).strip().upper().replace(" ", "")
    for band in sorted(BANDS, reverse=True):
        prefix = str(band)
        if text.startswith(prefix):
            cup = text[len(prefix) :]
            if cup in CUPS:
                return band, cup
    return None
